"""Small Freedom relay (SPEC §6.1): NIP-01 over websockets, SQLite storage, NIP-42 AUTH; write only for authenticated
pubkeys on the allowlist, read open. Good for tests and small groups; for production see README (nostr-rs-relay or
strfry with the allowlist generated by `python -m community allowlist build`).
"""
from __future__ import annotations

import asyncio
import collections
import json
import os
import secrets
import sqlite3
import threading
import time

from . import identity, nostr

MAX_MESSAGE = 256 * 1024
MAX_LIMIT = 1000          # rows per filter
MAX_REQ_ROWS = 2000       # rows per REQ over all its filters
MAX_FILTERS = 10          # filters per REQ
MAX_SUBS = 20             # open subscriptions per connection
RATE_WINDOW = 10.0        # seconds
RATE_MAX = 200            # messages per connection per window


class Store:
    def __init__(self, path: str):
        self.db = sqlite3.connect(path, check_same_thread=False)
        self.db.executescript("""
        CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, pubkey TEXT, kind INTEGER, created_at INTEGER,
          json TEXT, d TEXT);
        CREATE INDEX IF NOT EXISTS ev_kind ON events(kind, created_at);
        CREATE INDEX IF NOT EXISTS ev_author ON events(pubkey, created_at);
        CREATE TABLE IF NOT EXISTS tags (id TEXT, name TEXT, value TEXT);
        CREATE INDEX IF NOT EXISTS tags_nv ON tags(name, value);
        """)
        self.lock = threading.Lock()

    def save(self, ev: dict) -> str:
        """'' when stored, 'duplicate' or 'replaced-newer' otherwise. Replacing an addressable/replaceable event is
        one transaction (delete old + insert new + tags): on any error everything is rolled back (round-4 review)."""
        with self.lock:
            try:
                return self._save(ev)
            except Exception:
                self.db.rollback()
                raise

    def _save(self, ev: dict) -> str:
        if self.db.execute("SELECT 1 FROM events WHERE id=?", (ev["id"],)).fetchone():
            return "duplicate"
        d = None
        if nostr.is_addressable(ev["kind"]) or nostr.is_replaceable(ev["kind"]):
            d = nostr.d_tag(ev) if nostr.is_addressable(ev["kind"]) else ""
            old = self.db.execute("SELECT id, created_at FROM events WHERE kind=? AND pubkey=? AND d=?",
                                  (ev["kind"], ev["pubkey"], d)).fetchall()
            for o in old:
                # newest wins; equal created_at: the lower id wins (NIP-01)
                if o[1] > ev["created_at"] or (o[1] == ev["created_at"] and o[0] < ev["id"]):
                    return "replaced-newer"
            for o in old:
                self.db.execute("DELETE FROM events WHERE id=?", (o[0],))
                self.db.execute("DELETE FROM tags WHERE id=?", (o[0],))
        self.db.execute("INSERT INTO events VALUES (?,?,?,?,?,?)",
                        (ev["id"], ev["pubkey"], ev["kind"], ev["created_at"], json.dumps(nostr.canonical_event(ev)), d))
        self.db.executemany("INSERT INTO tags VALUES (?,?,?)",
                            [(ev["id"], t[0], t[1]) for t in ev["tags"] if len(t) >= 2 and len(t[0]) == 1])
        self.db.commit()
        return ""

    def query(self, f: dict, cap: int = MAX_LIMIT) -> list[dict]:
        """f must have passed nostr.filter_problem."""
        q, a = "SELECT json FROM events e WHERE 1=1", []
        for key, col in (("ids", "id"), ("authors", "pubkey"), ("kinds", "kind")):
            if key in f:
                vals = list(f[key])
                if not vals:
                    return []
                q += f" AND e.{col} IN ({','.join('?' * len(vals))})"
                a += vals
        if "since" in f:
            q += " AND e.created_at>=?"
            a.append(int(f["since"]))
        if "until" in f:
            q += " AND e.created_at<=?"
            a.append(int(f["until"]))
        for k, vals in f.items():
            if k.startswith("#") and len(k) == 2:
                vals = list(vals)
                q += f" AND e.id IN (SELECT id FROM tags WHERE name=? AND value IN ({','.join('?' * len(vals))}))"
                a += [k[1]] + vals
        lim = max(0, min(int(f.get("limit", MAX_LIMIT)), MAX_LIMIT, cap))
        q += " ORDER BY e.created_at DESC, e.id LIMIT ?"
        a.append(lim)
        with self.lock:
            return [json.loads(r[0]) for r in self.db.execute(q, a)]


class Relay:
    def __init__(self, db_path: str, url: str, allowlist_path: str | None = None, allowed=None,
                 auth_window: int = 600, rate_max: int = RATE_MAX, rate_window: float = RATE_WINDOW):
        self.store = Store(db_path)
        self.url = url
        self.allowlist_path = allowlist_path
        self._allowed = set(allowed or [])
        self._mtime = None
        self.auth_window = auth_window
        self._live: dict = {}
        self.log = collections.deque(maxlen=500)
        self.rate_max, self.rate_window = rate_max, rate_window

    def allowed(self) -> set:
        if self.allowlist_path:
            try:
                m = os.path.getmtime(self.allowlist_path)
                if m != self._mtime:
                    self._allowed, self._mtime = set(identity.load_allowlist(self.allowlist_path)["pubkeys"]), m
            except OSError:
                pass
        return self._allowed

    async def handler(self, ws):
        conn = {"ws": ws, "challenge": secrets.token_hex(16), "authed": set(), "subs": {},
                "times": collections.deque()}
        self._live[id(conn)] = conn
        try:
            await ws.send(json.dumps(["AUTH", conn["challenge"]]))
            async for raw in ws:
                if self._rate_limited(conn):
                    await self._send(conn, ["NOTICE", "rate-limited: slow down"])
                    continue
                try:
                    await self._on_message(conn, raw)
                except Exception as e:  # noqa: BLE001 - one bad message must not end the connection
                    self.log.append(f"error {type(e).__name__}")
                    await self._send(conn, ["NOTICE", "error: could not process the message"])
        except Exception:  # noqa: BLE001 - a broken client must not stop the relay
            pass
        finally:
            self._live.pop(id(conn), None)

    def _rate_limited(self, conn) -> bool:
        now, t = time.monotonic(), conn["times"]
        while t and now - t[0] > self.rate_window:
            t.popleft()
        if len(t) >= self.rate_max:
            return True
        t.append(now)
        return False

    async def _send(self, conn, msg):
        try:
            await conn["ws"].send(json.dumps(msg, ensure_ascii=False))
        except Exception:  # noqa: BLE001
            pass

    async def _on_message(self, conn, raw):
        try:
            msg = json.loads(raw)
            typ = msg[0]
        except (ValueError, IndexError, TypeError, KeyError):
            return await self._send(conn, ["NOTICE", "invalid: not a JSON array"])
        if typ == "EVENT" and len(msg) >= 2 and isinstance(msg[1], dict):
            return await self._on_event(conn, msg[1])
        if typ in ("REQ", "CLOSE"):
            sid = msg[1] if len(msg) >= 2 else None
            if not (isinstance(sid, str) and 0 < len(sid) <= 64 and nostr.utf8_ok(sid)):
                return await self._send(conn, ["CLOSED", "", "invalid: subscription id must be a string of 1-64 chars"])
            if typ == "REQ":
                if len(msg) < 3:
                    return await self._send(conn, ["CLOSED", sid, "invalid: REQ needs a filter"])
                return await self._on_req(conn, sid, msg[2:])
            conn["subs"].pop(sid, None)
            return await self._send(conn, ["CLOSED", sid, ""])
        if typ == "AUTH" and len(msg) >= 2 and isinstance(msg[1], dict):
            ev = msg[1]
            why = nostr.check_auth_event(ev, self.url, conn["challenge"], window=self.auth_window)
            if not why:
                conn["authed"].add(ev["pubkey"])
            return await self._send(conn, ["OK", ev.get("id", ""), not why, "" if not why else f"auth-required: {why}"])
        return await self._send(conn, ["NOTICE", f"unsupported message {typ!r}"])

    async def _on_event(self, conn, ev):
        eid = ev.get("id", "")
        if not nostr.verify_event(ev):
            return await self._send(conn, ["OK", eid, False, "invalid: bad id or signature"])
        if ev["kind"] == nostr.KIND_AUTH:
            return await self._send(conn, ["OK", eid, False, "invalid: auth events go in AUTH messages"])
        allowed = self.allowed()
        if not conn["authed"]:
            self.log.append(f"reject unauthenticated {eid[:8]}")
            return await self._send(conn, ["OK", eid, False, "auth-required: this relay accepts writes from "
                                                             "authenticated Freedom workbenches only"])
        if not conn["authed"] & allowed:
            self.log.append(f"reject not-allowed connection {eid[:8]}")
            return await self._send(conn, ["OK", eid, False, "restricted: your key is not on the allowlist"])
        if ev["pubkey"] not in allowed:
            return await self._send(conn, ["OK", eid, False, "restricted: event author is not on the allowlist"])
        if len(json.dumps(ev)) > MAX_MESSAGE:
            return await self._send(conn, ["OK", eid, False, "invalid: event too large"])
        if ev["created_at"] > time.time() + 900:
            return await self._send(conn, ["OK", eid, False, "invalid: created_at too far in the future"])
        ev = nostr.canonical_event(ev)
        if not nostr.is_ephemeral(ev["kind"]):
            r = await asyncio.to_thread(self.store.save, ev)      # SQLite off the event loop
            if r:
                return await self._send(conn, ["OK", eid, r == "duplicate", f"duplicate: {r}"])
        await self._send(conn, ["OK", eid, True, ""])
        for other in list(self._live.values()):
            for sid, filters in list(other["subs"].items()):
                try:                                              # one subscriber's problem stays its own
                    if nostr.match_any(ev, filters):
                        await self._send(other, ["EVENT", sid, ev])
                except Exception:  # noqa: BLE001
                    other["subs"].pop(sid, None)

    async def _on_req(self, conn, sid, filters):
        if len(conn["subs"]) >= MAX_SUBS and sid not in conn["subs"]:
            return await self._send(conn, ["CLOSED", sid, "error: too many subscriptions"])
        if not filters or len(filters) > MAX_FILTERS:
            return await self._send(conn, ["CLOSED", sid, f"invalid: 1-{MAX_FILTERS} filters per REQ"])
        for f in filters:
            why = nostr.filter_problem(f)
            if why:
                conn["subs"].pop(sid, None)
                return await self._send(conn, ["CLOSED", sid, f"invalid: {why}"])
        seen, left = set(), MAX_REQ_ROWS
        for f in filters:
            if left <= 0:
                break
            for ev in await asyncio.to_thread(self.store.query, f, left):
                if ev["id"] not in seen:
                    seen.add(ev["id"])
                    left -= 1
                    await self._send(conn, ["EVENT", sid, ev])
        await self._send(conn, ["EOSE", sid])
        conn["subs"][sid] = filters


async def serve(relay: Relay, host: str = "127.0.0.1", port: int = 7447):
    from websockets.asyncio.server import serve as ws_serve
    return await ws_serve(relay.handler, host, port, max_size=MAX_MESSAGE, close_timeout=2)


class RelayThread:
    """Relay in a background thread (tests, `relay serve`)."""

    def __init__(self, db_path: str, host: str = "127.0.0.1", port: int = 0, allowlist_path=None, allowed=None):
        self.host, self.port = host, port
        self.db_path, self.allowlist_path, self.allowed_init = db_path, allowlist_path, allowed
        self.relay: Relay | None = None
        self._ready = threading.Event()
        self._loop = None
        self._server = None

    def start(self):
        self._t = threading.Thread(target=self._run, daemon=True)
        self._t.start()
        if not self._ready.wait(10):
            raise RuntimeError("relay did not start")
        return self

    def _run(self):
        self._loop = asyncio.new_event_loop()
        asyncio.set_event_loop(self._loop)

        async def main():
            self.relay = Relay(self.db_path, "", self.allowlist_path, self.allowed_init)
            self._server = await serve(self.relay, self.host, self.port)
            self.port = self._server.sockets[0].getsockname()[1]
            self.relay.url = self.url
            self._ready.set()
            await self._server.wait_closed()
        try:
            self._loop.run_until_complete(main())
        finally:
            self._loop.close()

    @property
    def url(self) -> str:
        return f"ws://{self.host}:{self.port}"

    def stop(self):
        if self._loop and self._server:
            self._loop.call_soon_threadsafe(self._server.close)
            self._t.join(10)
